#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLI_COMMAND_CATALOGUE } from '../../packages/runtime/src/cli-catalogue.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const output = resolve(root, 'docs/cli-reference.md');
const check = process.argv.includes('--check');

function displayUsage(usage) {
  return usage
    .replace('q1x --home <path> ', 'q1x ')
    .replace('q1x --home <empty-target> ', 'q1x ');
}

const lines = [
  '# CLI Reference',
  '',
  '> Generated from `packages/runtime/src/cli-catalogue.ts`. Do not edit this file by hand.',
  '',
  'The `--home <path>` option selects a runtime home and may be placed anywhere in the command. Commands that do not need runtime state omit it.',
  '',
  '| Command | Purpose |',
  '| --- | --- |',
];
for (const command of CLI_COMMAND_CATALOGUE) {
  const usage = displayUsage(command.usage).replaceAll('|', '\\|');
  const purpose = command.purpose.replaceAll('|', '\\|');
  lines.push(`| \`${usage}\` | ${purpose} |`);
}

lines.push('', '## Runtime-home safety', '');
lines.push('Use a dedicated runtime home for each independent environment. Back up before upgrades or destructive recovery work.');
lines.push('`backup restore` requires an empty target home and fails closed rather than merging state.');
lines.push('', '## Output contract', '');
lines.push('Successful CLI commands emit one JSON value to standard output. Errors emit a JSON error object to standard error and return a non-zero exit code.');
lines.push('Do not place secrets in command arguments or persisted endpoint files; use environment-key mappings where supported.');

const rendered = `${lines.join('\n')}\n`;
if (check) {
  let current = '';
  try { current = await readFile(output, 'utf8'); } catch {}
  if (current !== rendered) {
    console.error('CLI reference is stale. Run node scripts/docs/generate-cli-reference.mjs.');
    process.exitCode = 1;
  }
} else {
  await writeFile(output, rendered, 'utf8');
  console.log(output);
}
